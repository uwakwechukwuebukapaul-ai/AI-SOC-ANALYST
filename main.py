# =====================================
# DOWNLOAD REPORT
# =====================================

@app.route(
    "/download_report/<int:id>"
)
def download_report(id):

    incident = get_incident(id)


    report = f"""

AI SOC INVESTIGATION REPORT


Incident:
{id}


Threat:
{incident["threat"]}


Severity:
{incident["severity"]}


Risk Score:
{incident["risk_score"]}


MITRE:
{incident["mitre"]}


Status:
{incident["status"]}


Generated:
{datetime.datetime.now()}

"""


    file = io.BytesIO(
        report.encode()
    )


    file.seek(0)


    return send_file(

        file,

        download_name=f"incident_{id}.txt",

        as_attachment=True

    )





