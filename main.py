from flask import (
    Flask,
    render_template,
    request,
    redirect,
    jsonify,
    send_file
)

from database import (
    get_incidents,
    get_incident,
    dashboard_stats,
    update_status,
    assign_analyst,
    add_notes
)

import datetime
import io


app = Flask(__name__)



# =====================================
# DASHBOARD HOME
# =====================================

@app.route("/")
def index():

    incidents = get_incidents()

    dashboard = dashboard_stats()

    alerts = []

    seen = set()


    for incident in incidents:

        threat = incident["threat"]

        severity = str(
            incident["severity"]
        ).upper()


        if severity == "HIGH" and threat not in seen:

            alerts.append({

                "type": threat,

                "severity": severity,

                "score": incident["risk_score"],

                "mitre": incident["mitre"]

            })


            seen.add(threat)



    analytics = {

        "average_risk":
        dashboard["average_risk"]

    }



    return render_template(

        "index.html",

        incidents=incidents,

        alerts=alerts,

        dashboard=dashboard,

        analytics=analytics

    )





# =====================================
# DASHBOARD API
# =====================================

@app.route("/api/dashboard")
def dashboard_api():

    incidents = get_incidents()

    stats = dashboard_stats()


    severity_data = {}

    attack_types = {}



    for incident in incidents:


        severity = incident["severity"]

        severity_data[severity] = (
            severity_data.get(severity,0)+1
        )


        attack = incident["threat"]

        attack_types[attack] = (
            attack_types.get(attack,0)+1
        )



    return jsonify({

        "total": stats["total"],

        "high": stats["high"],

        "open": stats["open"],

        "average_risk":
            stats["average_risk"],

        "severity_data":
            severity_data,

        "attack_types":
            attack_types

    })





